"""Where our own menu pieces (menu_art.py) sit in their sheets: the game set's HUD table's "ui"
cells. The patch gets a generated `menu_pieces.hpp` with each piece's cell in its sheet's pixels,
named after the piece and, for a tab, its word (kMenuPieceTabGear)."""

from __future__ import annotations

import json
from pathlib import Path


def _name(cell: dict) -> str:
    words = [cell["ui"], cell["word"]] if cell["ui"] == "tab" else [cell["ui"]]
    return "kMenuPiece" + "".join(word.capitalize() for word in words)


def generate(repo: Path, game: str, out: Path) -> Path | None:
    """`menu_pieces.hpp`; None for a game whose HUD table has no pieces."""
    table = json.loads((repo / "sets" / f"{game}.json").read_text()).get("hud")
    document = json.loads((repo / "sets" / table).read_text()) if table else {}
    pieces = [(path, cell) for path, cells in document.items() if isinstance(cells, list)
              for cell in cells if "ui" in cell]
    if not pieces:
        return None
    lines = [f"// Generated by tools/z3dmods/menu_pieces.py from sets/{table}; do not edit.", "#pragma once", "",
             f"namespace z3dmods::{game} {{", "",
             "// A piece's cell in its sheet's pixels (" + ", ".join(sorted({p for p, _ in pieces})) + "): its corner and size.",
             "struct MenuPiece {", "  float u;", "  float v;", "  float width;", "  float height;", "};", ""]
    for path, cell in pieces:
        x0, y0, x1, y1 = cell["box"]
        lines.append(f"inline constexpr MenuPiece {_name(cell)} = {{{x0}, {y0}, {x1 - x0}, {y1 - y0}}};")
    lines += ["", f"}} // namespace z3dmods::{game}", ""]
    out.mkdir(parents=True, exist_ok=True)
    header = out / "menu_pieces.hpp"
    header.write_text("\n".join(lines))
    return header
