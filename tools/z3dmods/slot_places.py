"""Where the game draws each item slot on a screen that assigns them: hud.toml's `[[slot]]`s and
`[[slot_label]]`s, and the sheet of their labels (`[slot_labels]`). The patch gets a generated
`slot_places.hpp` with every device's places, in the top screen's 400x240 pixels, and the labels'
cells in the sheet's own pixels."""

from __future__ import annotations

import tomllib
from pathlib import Path

from z3dmods import slot_link


def _device(entry: dict, path: Path) -> str:
    names = [d for d in slot_link.DEVICES if d.lower() == entry["device"]]
    if not names:
        raise SystemExit(f"{path}: no device {entry['device']!r}")
    return f"HostDevice::{names[0]}"


def generate(repo: Path, game: str, out: Path) -> Path | None:
    """`kSlotPlaces` and `kSlotLabels`; None for a game without slots."""
    path = repo / "patch" / game / "hud.toml"
    table = tomllib.loads(path.read_text()) if path.exists() else {}
    if "slot" not in table:
        return None
    sheet = table["slot_labels"]
    slots, labels = table["slot"], table.get("slot_label", [])
    if any(e["rect"][2] != e["rect"][3] for e in slots + labels):
        raise SystemExit(f"{path}: a slot's rect is a square")
    places = [f"  {{{_device(e, path)}, {e['slot']}, {e['rect'][0]}, {e['rect'][1]}, {e['rect'][2]}, "
              f"{'false' if e.get('bare') else 'true'}}}," for e in slots]
    lone = [f"  {{{_device(e, path)}, {e['cell'][0]}, {e['cell'][1]}, {e['rect'][0]}, {e['rect'][1]}, "
            f"{e['rect'][2]}}}," for e in labels]
    lines = [f"// Generated by tools/z3dmods/slot_places.py from patch/{game}/hud.toml; do not edit.",
             "#pragma once", "", '#include "slot_link.hpp"', "", "#include <stdint.h>", "",
             f"namespace z3dmods::{game} {{", "",
             "// The labels' sheet, its size, its cells' side and slot 0's cell, in its pixels.",
             f"inline constexpr char kSlotLabelSheet[] = \"{sheet['sheet']}\";",
             f"inline constexpr float kSlotLabelSheetSize[2] = {{{sheet['size'][0]}, {sheet['size'][1]}}};",
             f"inline constexpr int16_t kSlotLabelCell = {sheet['cell']};",
             f"inline constexpr int16_t kSlotLabelRow[2] = {{{sheet['row'][0]}, {sheet['row'][1]}}};", "",
             "// A slot's button on a device: its square in the top screen's pixels, and whether it is",
             "// labelled.",
             "struct SlotPlace {", "  HostDevice device;", "  uint8_t slot;", "  int16_t x;", "  int16_t y;",
             "  int16_t size;", "  bool labelled;", "};", "",
             "// A label on its own: its cell in the sheet and its square.",
             "struct SlotLabel {", "  HostDevice device;", "  int16_t u;", "  int16_t v;", "  int16_t x;",
             "  int16_t y;", "  int16_t size;", "};", "",
             "inline constexpr SlotPlace kSlotPlaces[] = {", *places, "};",
             "inline constexpr SlotLabel kSlotLabels[] = {", *lone, "};",
             "", f"}} // namespace z3dmods::{game}", ""]
    out.mkdir(parents=True, exist_ok=True)
    header = out / "slot_places.hpp"
    header.write_text("\n".join(lines))
    return header
